"""
Generate the documentation in docs/ from the single sources of truth:

    docs/DATA_DICTIONARY.md  <- database/schema/schema.sql  (+ allowed values from the validator)
    docs/ERD.md              <- schema.sql foreign keys      (Mermaid diagram, rendered by GitHub)
    docs/RULES.md            <- generator/rules.py
    docs/API.md              <- FastAPI OpenAPI schema (app.main)

    cd backend
    python -m scripts.build_docs

No database connection is needed. Re-run after changing the schema, rules or API.
"""
import re
from pathlib import Path

from app.core.config import PROJECT_ROOT, SCHEMA_DIR
from app.services.meta_service import RELATIONSHIPS, business_rules, data_dictionary

DOCS = PROJECT_ROOT / "docs"


def _cell(v) -> str:
    if v is None or v == "" or v == []:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, list):
        return ", ".join(str(x) for x in v)
    return str(v).replace("|", "\\|")


# ------------------------------------------------------------------ data dictionary
def build_data_dictionary() -> str:
    dd = data_dictionary()
    out = ["# Data Dictionary", "",
           "Generated by `python -m scripts.build_docs` from `database/schema/schema.sql` "
           "(single source of truth for Tier 3). Allowed values come from the validator / business rules.", "",
           "## Entities", "", "| Table | Kind | Primary key | Lifecycle states | Description |",
           "|---|---|---|---|---|"]
    for t in dd["tables"]:
        out.append(f"| `{t['table']}` | {t['kind']} | `{', '.join(t['primary_key'])}` | {_cell(t['lifecycle'])} "
                   f"| {t['description']} |")
    out += ["", "## Relationships and cardinality", "", "| Parent | Cardinality | Child | Via | Optional |",
            "|---|---|---|---|---|"]
    for r in dd["relationships"]:
        out.append(f"| `{r['parent']}` | **{r['cardinality']}** | `{r['child']}` | `{r['via']}` | {_cell(r['optional'])} |")
    out += ["", "## ID conventions", "", "| Entity | Format |", "|---|---|"]
    out += [f"| {k} | `{v}` |" for k, v in dd["id_conventions"].items()]
    out += ["", "IDs are zero-padded, immutable and generated only by `backend/generator/id_factory.py`.", ""]
    for t in dd["tables"]:
        out += [f"## `{t['table']}`", "", f"{t['description']}  ", f"**Kind:** {t['kind']} · "
                f"**Primary key:** `{', '.join(t['primary_key'])}`" +
                (f" · **Lifecycle:** {t['lifecycle']}" if t["lifecycle"] else ""), "",
                "| Field | Type | Required | Allowed values | Units | Unique | FK | Validation rule |",
                "|---|---|---|---|---|---|---|---|"]
        for f in t["fields"]:
            name = f"**{f['field']}**" if f["primary_key"] else f["field"]
            out.append(f"| {name} | `{f['type']}` | {_cell(f['required'])} | {_cell(f['allowed_values'])} | "
                       f"{_cell(f['units'])} | {_cell(f['unique'])} | {_cell(f['foreign_key'])} | {_cell(f['validation'])} |")
        out.append("")
    return "\n".join(out)


# ------------------------------------------------------------------ ERD (Mermaid)
def build_erd() -> str:
    sql = (SCHEMA_DIR / "schema.sql").read_text(encoding="utf-8")
    entities, rels = [], []
    for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\) ENGINE", sql, re.S):
        name, body = m.group(1), m.group(2)
        pk = re.search(r"PRIMARY KEY \(([^)]+)\)", body).group(1).replace(" ", "").split(",")
        uniques = {u.strip() for g in re.findall(r"UNIQUE KEY \w+ \(([^)]+)\)", body) for u in g.split(",")}
        fks = {c: t for c, t in re.findall(r"FOREIGN KEY \((\w+)\)\s+REFERENCES (\w+)", body)}
        cols = []
        for line in body.splitlines():
            fm = re.match(r"\s{4}(\w+)\s+([A-Z]+)(?:\([\d,]+\))?\s+(NOT NULL|NULL)", line)
            if not fm:
                continue
            col, typ, null = fm.groups()
            keys = ",".join(k for k, ok in (("PK", col in pk), ("FK", col in fks), ("UK", col in uniques)) if ok)
            cols.append(f"        {typ} {col}{(' ' + keys) if keys else ''}")
            if col in fks:
                parent = fks[col]
                if col in uniques:
                    card = "||--o|"                  # 1 : 0..1
                elif null == "NULL":
                    card = "|o--o{"                  # optional parent
                else:
                    card = "||--o{"                  # 1 : N
                rels.append(f'    {parent} {card} {name} : "{col}"')
        entities.append(f"    {name} {{\n" + "\n".join(cols) + "\n    }")
    mermaid = "\n".join(["```mermaid", "erDiagram", *rels, *entities, "```"])
    return "\n".join([
        "# Entity-Relationship Diagram", "",
        "Generated from the foreign keys in `database/schema/schema.sql`. GitHub renders the Mermaid diagram below.", "",
        "* `||--o{` one-to-many · `||--o|` one-to-zero-or-one · `|o--o{` optional parent",
        "* Many-to-many relationships use bridge tables: **machine_zone** (machine ↔ safety_zone) and "
        "**incident_alarm** (incident ↔ alarm_event, role TRIGGER / CONTEXT)",
        "* History tables (`machine_state_event`, `interlock_state_event`) are append-only - state is never overwritten", "",
        mermaid, "",
        "## Cardinality summary", "", "| Parent | Cardinality | Child | Via |", "|---|---|---|---|",
        *[f"| `{p}` | **{c}** | `{ch}` | `{v}` |" for p, ch, c, v, _ in RELATIONSHIPS], ""])


# ------------------------------------------------------------------ rules
def build_rules() -> str:
    r = business_rules()
    out = ["# Business Rules", "",
           "Single source of truth: `backend/generator/rules.py`. The **same rules generate the data and analyse it**, "
           "so outcomes and labels are derived from documented rules - never assigned at random.", "",
           "## 1. Severity, priority weight and acknowledgement SLA", "",
           "| Severity | Priority weight | Ack SLA (s) |", "|---|---|---|"]
    out += [f"| {s['severity']} | {s['weight']} | {s['ack_sla_sec']} |" for s in r["severity"]]
    out += ["", f"**Priority score** = `{r['priority_formula']}`  ",
            "Interlock factor: " + ", ".join(f"{k} ×{v}" for k, v in r["interlock_factor"].items()) + ".  ",
            "A delayed acknowledgement is `response_sec > ack SLA`; `response_sec = ack_ts − raised_ts` (derived).", "",
            "## 2. Incident rules (incidents are derived from the data)", "", "| Rule | Condition | Severity |",
            "|---|---|---|"]
    out += [f"| `{i['rule_code']}` | {i['description']} | {i['severity']} |" for i in r["incident_rules"]]
    out += ["", f"**Repeated unsafe condition:** the same machine and the same rule at least "
            f"{r['repeated_unsafe']['min_count']} times within a rolling {r['repeated_unsafe']['window_days']} days.", "",
            "## 3. Alarm management (ISA-18.2 inspired)", "",
            f"* **Alarm flood:** {r['flood']['text']} (replay duplicates and chattering alarms excluded first).",
            f"* **Chattering:** ≥ {r['nuisance']['chatter_min_count']} activations of the same alarm on the same machine "
            f"within {r['nuisance']['chatter_window_sec']} s = one chatter episode.",
            f"* **Nuisance alarm (bad actor):** ≥ {r['nuisance']['nuisance_min_episodes']} chatter episodes.",
            f"* **Fleeting alarm:** cleared within {r['nuisance']['fleeting_max_sec']} s.",
            "* **Replay duplicate:** same `(machine_id, alarm_def_id, source_seq)` - the later-received copy is the replay.", "",
            "## 4. State machines and lifecycles", "", "**Machine**", "", "| From | Allowed next states |", "|---|---|"]
    out += [f"| {k} | {', '.join(v)} |" for k, v in r["machine_transitions"].items()]
    out += ["", "**Interlock**", "", "| From | Allowed next states |", "|---|---|"]
    out += [f"| {k} | {', '.join(v)} |" for k, v in r["interlock_transitions"].items()]
    out += ["", "A TRIPPED interlock must stop the machine: an interlock trip recorded while the machine is RUNNING is "
            "an *impossible state*.", "",
            f"**Incident lifecycle:** {' → '.join(r['incident_statuses'])} (status derived from its corrective actions)  ",
            f"**Corrective-action lifecycle:** {' → '.join(r['action_statuses'])} "
            "(an action may only be CLOSED after it is VERIFIED)", "",
            "**Shifts:** " + ", ".join(f"{k} {v}" for k, v in r["shifts"].items()), "",
            "## 5. Labelled edge cases and expected decisions", "", "| Issue / pattern | Expected decision |", "|---|---|"]
    out += [f"| `{k}` | `{v}` |" for k, v in r["expected_decisions"].items()]
    g = r["generator"]
    out += ["", "## 6. Generator", "", f"* Seed: `{g['seed']}`", f"* Command: `{g['command']}`", "",
            "| Scale | Plants | Machines | Alarm definitions | Alarm events | Days |", "|---|---|---|---|---|---|"]
    out += [f"| {k} | {v['plants']} | {v['machines']} | {v['alarm_definitions']} | {v['alarm_events']} | {v['days']} |"
            for k, v in g["scales"].items()]
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ API
def build_api() -> str:
    from app.main import app
    spec = app.openapi()
    out = ["# REST API", "",
           "Base URL: `http://localhost:8000` · Interactive docs (Swagger): `http://localhost:8000/docs`", "",
           "All errors use one JSON shape: "
           "`{\"error\": {\"code\", \"message\", \"path\", \"details\"}}` with codes "
           "`BAD_REQUEST` (400), `NOT_FOUND` (404), `VALIDATION_ERROR` (422), `DATABASE_UNAVAILABLE` (503), "
           "`INTERNAL_ERROR` (500).", "",
           "| Method | Path | Description | Query / path parameters |", "|---|---|---|---|"]
    for path, ops in sorted(spec["paths"].items()):
        for method, op in ops.items():
            params = []
            for p in op.get("parameters", []):
                sch = p.get("schema", {})
                options = sch.get("enum") or next((x.get("enum") for x in sch.get("anyOf", []) if x.get("enum")), None)
                hint = f" ({'/'.join(options)})" if options else ""
                params.append(f"`{p['name']}`{hint}")
            desc = (op.get("description") or op.get("summary") or "").split("\n")[0].replace("|", "\\|")
            out.append(f"| {method.upper()} | `{path}` | {desc} | {', '.join(params) or '-'} |")
    return "\n".join(out) + "\n"


def main():
    DOCS.mkdir(exist_ok=True)
    files = {"DATA_DICTIONARY.md": build_data_dictionary(), "ERD.md": build_erd(),
             "RULES.md": build_rules(), "API.md": build_api()}
    for name, text in files.items():
        (DOCS / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote docs/{name:<20} {len(text.splitlines()):>4} lines")
    gk = DOCS / ".gitkeep"
    if gk.exists():
        gk.unlink()


if __name__ == "__main__":
    main()